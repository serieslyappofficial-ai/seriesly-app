function detectPlatformFromValue(value) {
  const v = (value || "").toLowerCase();
  if (v.includes("instagram.com")) return "instagram";
  if (v.includes("tiktok.com")) return "tiktok";
  if (v.includes("x.com") || v.includes("twitter.com")) return "x";
  if (v.includes("youtube.com") || v.includes("youtu.be")) return "youtube";
  return "outro";
}

function renderStats(items) {
  const list = document.getElementById("stats-list");
  if (!list) return;
  list.innerHTML = "";
  if (!items || items.length === 0) {
    const li = document.createElement("li");
    li.className = "muted";
    li.textContent = translations[currentLang].statsEmpty;
    list.appendChild(li);
    return;
  }

  const total = items.length;
  const perPlatform = { instagram: 0, tiktok: 0, x: 0, youtube: 0, outro: 0 };
  items.forEach((it) => {
    const p = detectPlatformFromValue(it.value);
    if (perPlatform[p] !== undefined) perPlatform[p] += 1;
    else perPlatform.outro += 1;
  });

  const row = (label, value) => {
    const li = document.createElement("li");
    const spanLabel = document.createElement("span");
    spanLabel.textContent = label;
    const spanVal = document.createElement("span");
    spanVal.className = "value";
    spanVal.textContent = value;
    li.appendChild(spanLabel);
    li.appendChild(spanVal);
    list.appendChild(li);
  };

  row(currentLang === "pt" ? "Itens salvos" : "Saved items", String(total));
  row("Instagram", String(perPlatform.instagram));
  row("TikTok", String(perPlatform.tiktok));
  row("X", String(perPlatform.x));
  row("YouTube", String(perPlatform.youtube));
}

