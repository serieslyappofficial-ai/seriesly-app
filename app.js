const AI_ENDPOINT = "/api/seriesly-ai"; // Ajuste para o endpoint real do seu backend

function getChatHistoryForServer() {
  try {
    const history = JSON.parse(localStorage.getItem("seriesly_chat") || "[]");
    return history.slice(-20);
  } catch {
    return [];
  }
}

async function botAnswer(userText) {
  const fallback = botAnswerLocal(userText);
  try {
    const res = await fetch(AI_ENDPOINT, {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({
        message: userText,
        history: getChatHistoryForServer(),
      }),
    });
    if (!res.ok) throw new Error("Bad status");
    const data = await res.json();
    if (data && data.reply) return data.reply;
    return fallback;
  } catch (err) {
    return fallback;
  }
}

function initChat() {
  const box = document.getElementById("chat-box");
  if (!box) return;
  // Load from localStorage
  try {
    const saved = JSON.parse(localStorage.getItem("seriesly_chat") || "[]");
    box.innerHTML = "";
    saved.forEach((m) => appendChatMessage(m.role, m.text, false));
  } catch {
    box.innerHTML = "";
  }
  if (box.children.length === 0) {
    appendChatMessage(
      "bot",
      currentLang === "pt"
        ? "Olá! Sou o bot do Seriesly. Como posso ajudar? (ex: login, planos, salvar links, buscar perfis, foto do perfil)"
        : "Hi! I'm Seriesly's bot. How can I help? (e.g., login, plans, saving links, profile search, avatar)",
      true
    );
  }
}

function appendChatMessage(role, text, persist = true) {
  const box = document.getElementById("chat-box");
  if (!box) return;
  const div = document.createElement("div");
  div.className = `chat-bubble ${role}`;
  div.textContent = text;
  box.appendChild(div);
  box.scrollTop = box.scrollHeight;

  if (persist) {
    const history = JSON.parse(localStorage.getItem("seriesly_chat") || "[]");
    history.push({ role, text });
    localStorage.setItem("seriesly_chat", JSON.stringify(history.slice(-40)));
  }
}

